import { createSlice, PayloadAction } from "@reduxjs/toolkit";
import { formatDateLong } from "@/lib/dateUtils";

/** Redux state for selecting and locking the day's Morning 3 tasks. */
export interface MorningState {
  /** Date on which the selected tasks were locked, formatted as YYYY-MM-DD; null when not locked. */
  picksLockedForDate: string | null,
  /** IDs of tasks currently selected for Morning 3. */
  pickedTaskIds: string[],
  /** Whether the user has completed the task-selection step. */
  selectionComplete: boolean
}

/** Initial Morning 3 state before any tasks are selected or locked. */
const initialState : MorningState = {
  picksLockedForDate: null,
  pickedTaskIds: [],
  selectionComplete: false
}

/** Reducers for managing the Morning 3 task selection and daily lock. */
export const morning3Slice = createSlice({
  name: 'morning3',
  initialState,
  reducers: {
    /** 
     * Toggles a task in the selected Morning 3 task IDs.
     *
     * @param state - The current Morning 3 state, updated using Immer.
     * @param action - The action containing the task ID to toggle.
     * @param action.payload - The payload containing the task ID.
     * @param action.payload.nodeID - ID of the task to add or remove.
     */
    togglePick: (state: MorningState, { payload: { nodeID }}: PayloadAction<{nodeID: string}>) => {
      const indexOfNodeID: number = state.pickedTaskIds.indexOf(nodeID);
      if (indexOfNodeID != -1) {
        state.pickedTaskIds.splice(indexOfNodeID, 1)
      } else {
        state.pickedTaskIds.push(nodeID)
      }
    },

    /**
     *  Locks the current selection to today's date.
     *
     * @param state - The current Morning 3 state, updated using Immer.
     */
    lockPicksToDate: (state: MorningState) => {
      state.picksLockedForDate = formatDateLong(new Date())
    }
  }
})

/** Actions generated by the Morning 3 slice reducers. */
export const {  } = morning3Slice.actions;

/** Reducer for the Morning 3 Redux state. */
export default morning3Slice.reducer;